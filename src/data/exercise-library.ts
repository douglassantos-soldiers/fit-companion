export interface LibraryExercise {
  id: string;
  name: string;
  group: MuscleGroup;
  equipment: Exercise["equipment"];
  swapGroup: string;
  joints: Joint[];
  unit: Exercise["unit"];
  baseLoad: number;
  priority: number;
  primaryMuscles: MuscleGroup[];
  secondaryMuscles: MuscleGroup[];
  movementPattern: MovementPattern;
  difficulty: Difficulty;
  plannerEligible: boolean;
  active: boolean;
  instructions: string[];
  animationSpec: AnimationSpec;
}

const SPEC: Pick<AnimationSpec, "tempo" | "durationSec" | "loop" | "camera"> = {
  tempo: "controlled",
  durationSec: 4,
  loop: true,
  camera: "three-quarter",
};

function ex(
  partial: Omit<LibraryExercise, "active" | "animationSpec" | "primaryMuscles"> & {
    start: string;
    end: string;
    tempo?: AnimationSpec["tempo"];
    camera?: AnimationSpec["camera"];
  },
): LibraryExercise {
  return {
    ...partial,
    primaryMuscles: [partial.group],
    active: true,
    animationSpec: {
      start: partial.start,
      end: partial.end,
      tempo: partial.tempo ?? SPEC.tempo,
      durationSec: SPEC.durationSec,
      loop: SPEC.loop,
      camera: partial.camera ?? SPEC.camera,
    },
  };
}

