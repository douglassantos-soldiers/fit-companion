/**
 * Writes dist/server/server.js so `vite preview` can load the Nitro Cloudflare
 * build from .output/server/index.mjs (TanStack expects dist/server/*.js).
 *
 * Mirrors @lovable.dev/vite-tanstack-config prerender preview shim.
 *
 * Usage: node scripts/write-preview-shim.mjs
 *        (called by npm run preview)
 */
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const NITRO_SERVER_ENTRY = "index.mjs";
const NITRO_WRANGLER_CONFIG = "wrangler.json";
const SHIM_MARKER =
  "// Generated by scripts/write-preview-shim.mjs for vite preview (Nitro Cloudflare → dist/server).";

const entryCandidates = [
  join(root, ".output", "server"),
  join(root, "dist", "server"),
];
const shimDir = join(root, "dist", "server");
const shimPath = join(shimDir, "server.js");

function shimSource(vars, entrySpecifier) {
  return `${SHIM_MARKER}
import server from "${entrySpecifier}";

const env = ${JSON.stringify(vars)};
const ctx = { waitUntil() {}, passThroughOnException() {}, props: {} };

export default {
  fetch(request) {
    // srvx's NodeRequest exposes \`ip\` as a getter-only accessor and nitro's
    // cloudflare module handler assigns to it; shadow it with a writable one.
    Object.defineProperty(request, "ip", { value: undefined, writable: true, configurable: true });
    return server.fetch(request, env, ctx);
  },
};
`;
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

let entryDir;
for (const candidate of entryCandidates) {
  if (await exists(join(candidate, NITRO_SERVER_ENTRY))) {
    entryDir = candidate;
    break;
  }
}

if (!entryDir) {
  console.error(
    "[write-preview-shim] Missing .output/server/index.mjs (and dist/server/index.mjs).\n" +
      "Run `npm run build` first, then `npm run preview`.",
  );
  process.exit(1);
}

let vars = {};
try {
  const wrangler = JSON.parse(await readFile(join(entryDir, NITRO_WRANGLER_CONFIG), "utf8"));
  const candidate = wrangler?.vars;
  if (candidate && typeof candidate === "object" && !Array.isArray(candidate)) vars = candidate;
} catch {
  /* optional */
}

const specifierRaw = relative(shimDir, join(entryDir, NITRO_SERVER_ENTRY)).split(sep).join("/");
const specifier = specifierRaw.startsWith(".") ? specifierRaw : `./${specifierRaw}`;

await mkdir(shimDir, { recursive: true });
await writeFile(shimPath, shimSource(vars, specifier));
console.log(`[write-preview-shim] wrote ${relative(root, shimPath)} → ${specifier}`);
