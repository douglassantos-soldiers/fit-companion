/**
 * Shared helpers for motion backlog queue (240 exercises / 6 batches).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSoldiersLibrary } from "../exercise-catalog/parse-library.mjs";

export const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const QUEUE_PATH = join(root, "content/soldiers-media-v1/queues/motion-backlog-v1.json");
export const PUBLISHED_JSON_PATH = join(
  root,
  "content/soldiers-media-v1/queues/published-exercises.json",
);
export const PUBLISHED_TS_PATH = join(root, "src/data/soldiers-media-published-ids.ts");

export const PILOT_EXERCISE_IDS = [
  "supino-reto",
  "flexao",
  "remada-curvada",
  "barra-fixa",
  "agachamento",
  "terra-romeno",
  "desenvolvimento",
  "elevacao-lateral",
  "rosca-direta",
  "prancha",
];

export const BATCH_COUNT = 6;
export const BATCH_SIZE = 40;

const HOLD_ID_RE =
  /(?:^|-)(prancha|plank|hold|wall-sit|hollow|l-sit|chin-hold|diamond-hold|handstand|copenhagen)/i;

export function isHoldExercise(row) {
  if (row.movementPattern === "isometric") return true;
  if (HOLD_ID_RE.test(row.id)) return true;
  const tempo = row.animationSpec?.tempo;
  if (tempo === "isometric") return true;
  return false;
}

export function loadQueue() {
  if (!existsSync(QUEUE_PATH)) return null;
  return JSON.parse(readFileSync(QUEUE_PATH, "utf8"));
}

export function loadPublishedIds() {
  if (existsSync(PUBLISHED_JSON_PATH)) {
    const raw = JSON.parse(readFileSync(PUBLISHED_JSON_PATH, "utf8"));
    const ids = Array.isArray(raw) ? raw : (raw.ids ?? []);
    return [...new Set(ids.map(String))];
  }
  return [...PILOT_EXERCISE_IDS];
}

export function writePublishedIds(ids) {
  const unique = [...new Set(ids)].sort((a, b) => a.localeCompare(b));
  mkdirSync(dirname(PUBLISHED_JSON_PATH), { recursive: true });
  writeFileSync(
    PUBLISHED_JSON_PATH,
    `${JSON.stringify({ version: 1, ids: unique }, null, 2)}\n`,
  );
  const ts = `/**
 * Auto-generated by media:promote / media:queue — do not edit by hand.
 * Pilot + promoted exercise IDs that are published in the Soldiers media manifest.
 */
export const PUBLISHED_EXERCISE_IDS = [
${unique.map((id) => `  "${id}",`).join("\n")}
] as const;

export type PublishedExerciseId = (typeof PUBLISHED_EXERCISE_IDS)[number];
`;
  writeFileSync(PUBLISHED_TS_PATH, ts);
  return unique;
}

export function buildMotionQueue() {
  const library = parseSoldiersLibrary(root);
  const pilot = new Set(PILOT_EXERCISE_IDS);
  const backlog = library
    .filter((row) => !pilot.has(row.id))
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((row, index) => ({
      kind: "exercise",
      id: row.id,
      name: row.name,
      batch: Math.floor(index / BATCH_SIZE) + 1,
      duration: row.animationSpec?.durationSec || 4,
      hold: isHoldExercise(row),
      start: row.animationSpec?.start || "",
      end: row.animationSpec?.end || "",
      movementPattern: row.movementPattern || "",
    }));

  const byBatch = {};
  for (let b = 1; b <= BATCH_COUNT; b += 1) {
    byBatch[b] = backlog.filter((r) => r.batch === b).length;
  }

  return {
    version: 1,
    generatedAt: new Date().toISOString(),
    total: backlog.length,
    batchCount: BATCH_COUNT,
    batchSize: BATCH_SIZE,
    byBatch,
    pilotExcluded: PILOT_EXERCISE_IDS,
    items: backlog,
  };
}

export function itemsForBatch(queue, batchNum) {
  return (queue.items ?? []).filter((item) => item.batch === Number(batchNum));
}

export function parseArg(name, fallback = null) {
  const idx = process.argv.indexOf(name);
  if (idx < 0) return fallback;
  return process.argv[idx + 1] ?? fallback;
}

export function packageComplete(dir) {
  const poster =
    existsSync(join(dir, "poster.webp")) || existsSync(join(dir, "poster.png"));
  const thumb =
    existsSync(join(dir, "thumb.webp")) ||
    existsSync(join(dir, "thumb.png")) ||
    poster;
  const motion =
    existsSync(join(dir, "animation.webm")) || existsSync(join(dir, "animation.mp4"));
  return poster && thumb && motion;
}
